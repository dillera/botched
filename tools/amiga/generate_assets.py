#!/usr/bin/env python3
"""Pack approved A2b art into bounded 4bpp ROM data; build needs no Python/Pillow."""
import importlib.util
import sys
sys.dont_write_bytecode = True
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('art',ROOT/'docs/amiga/a2b/render_mockups.py')
a=importlib.util.module_from_spec(spec);spec.loader.exec_module(a)
images=[a.tile(t) for t in ['.','#','S1','D1','G1','C^A','TA','L^','O','X1','A','Y1','P1','K1']]
images += [a.tile('C'+d+'A') for d in '^>v<']
images += [a.tile('D'+str(i)) for i in range(1,5)]
for p in range(1,5):
 for d in 'NESW':
  im=a.new(16,16);a.robot(im,0,0,p,d);images.append(im)
im=a.new(16,16);a.crate(im,0,0);images.append(im)
images += [a.tile('L'+d) for d in '^>v<']
images += [a.tile('S'+str(i)) for i in range(1,5)]
for i in range(9):
 im=a.new(16,16);a.order_icon(im,0,0,i);images.append(im)
assert len(images)==56
with (ROOT/'client/amiga/assets_data.h').open('w') as f:
 f.write('/* Generated by tools/amiga/generate_assets.py; approved A2b pixel art. */\nstatic const uint8_t pixels[56][128] = {\n')
 for im in images:
  data=list(im.tobytes());assert all(0<=v<16 for v in data)
  packed=[data[i]|(data[i+1]<<4) for i in range(0,256,2)]
  f.write('{'+','.join(str(v) for v in packed)+'},\n')
 f.write('};\n')
 # glyph scanlines, six pixels advance, five ink pixels. ASCII lower maps to upper.
 f.write('const uint8_t ba_glyphs[96][8] = {\n')
 for code in range(32,128):
  rows=a.DATA.get(chr(code).upper(),'').split('/')
  values=[sum((int(v)<< (7-i)) for i,v in enumerate(row)) for row in rows]
  values=(values+[0]*8)[:8]
  f.write('{'+','.join(str(v) for v in values)+'},\n')
 f.write('};\n')
print('56 sprites: 7168 packed bytes; font: 768 bytes.')
